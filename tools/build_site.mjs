// Builds the website's copy of the room-code decoder (docs/join_code.js) from
// shared/src/join_code.ts. Run after changing join_code.ts: node tools/build_site.mjs
import { writeFile } from "node:fs/promises";
import { build } from "esbuild";

await build({
  entryPoints: ["shared/src/join_code.ts"],
  outfile: "docs/join_code.js",
  bundle: true,
  format: "esm",
  target: "es2020",
  banner: { js: "// Generated by tools/build_site.mjs from shared/src/join_code.ts. Do not edit." },
  logLevel: "warning",
});
console.log("Wrote docs/join_code.js");

// Type declarations so the tests can check the website's copy.
await writeFile(
  "docs/join_code.d.ts",
  `// Generated by tools/build_site.mjs. Do not edit.
export declare const JOIN_CODE_ALPHABET: string;
export declare function encodeJoinCode(address: string): string | null;
export declare function decodeJoinCode(code: string): string | null;
export declare function pickLanAddress(addresses: string[]): string | null;
`,
);
